const fs = require("fs");
const os = require("os");
const path = require("path");

const API_PORT = 8000;
const outputPath = path.join(__dirname, "..", "src", "config", "generatedApi.ts");

function isPrivateIPv4(address) {
  return (
    address.startsWith("10.") ||
    address.startsWith("192.168.") ||
    /^172\.(1[6-9]|2\d|3[0-1])\./.test(address)
  );
}

function scoreAddress(name, address) {
  let score = 0;
  const label = name.toLowerCase();

  if (isPrivateIPv4(address)) {
    score += 100;
  }

  if (label.includes("wi-fi") || label.includes("wifi") || label.includes("wlan")) {
    score += 40;
  }

  if (label.includes("ethernet")) {
    score += 25;
  }

  if (address.startsWith("169.254.")) {
    score -= 100;
  }

  if (
    label.includes("virtual") ||
    label.includes("vmware") ||
    label.includes("virtualbox") ||
    label.includes("wsl") ||
    label.includes("loopback")
  ) {
    score -= 50;
  }

  return score;
}

function getBestAddress() {
  const candidates = [];
  const interfaces = os.networkInterfaces();

  for (const [name, addresses] of Object.entries(interfaces)) {
    for (const info of addresses ?? []) {
      if (info.family !== "IPv4" || info.internal) {
        continue;
      }

      candidates.push({
        name,
        address: info.address,
        score: scoreAddress(name, info.address),
      });
    }
  }

  candidates.sort((a, b) => b.score - a.score);
  return candidates[0];
}

const selected = getBestAddress();
const host = selected?.address ?? "localhost";
const baseUrl = `http://${host}:${API_PORT}`;

const file = `// This file is generated by scripts/generate-api-config.js.
// Run npm start again if your network changes.

export const GENERATED_BASE_URL = "${baseUrl}";
`;

fs.writeFileSync(outputPath, file);

console.log(
  `[api] generated ${baseUrl}${selected ? ` from ${selected.name}` : ""}`,
);
